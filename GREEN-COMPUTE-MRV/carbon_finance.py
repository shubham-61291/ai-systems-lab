def format_markdown(text):
    text = re.sub(r'\*\*(.*?)\*\*', r'<b>\1</b>', text) # Bold
    text = re.sub(r'### (.*)', r'<font size="12" color="#2E86C1"><b>\1</b></font><br/>', text) # Headers
    return text.replace('\n', '<br/>')

