def run_strategic_audit(home_zone_name, dur, comp_key):
    kw = COMPUTE_SPECS[comp_key]

    # --- DOMESTIC ENGINE ---
    dom_data = {}
    for name, code in DOMESTIC_ZONES.items():
        dom_data[name] = fetch_live_intensity(code)

    # Baseline
    home_intensity = dom_data.get(home_zone_name, FALLBACK_INTENSITY)

    # Find Best Domestic
    # Use key=dom_data.get to find key with min value
    best_dom_name = min(dom_data, key=dom_data.get)
    best_dom_val = dom_data[best_dom_name]

    dom_base = home_intensity * kw * dur
    dom_opt = best_dom_val * kw * dur
    dom_red = dom_base - dom_opt

    dom_res = {
        "home_intensity": home_intensity,
        "best_zone": best_dom_name, # THIS NOW PASSES THE FULL NAME (e.g. "North-East India (Assam)")
        "best_intensity": best_dom_val,
        "base": dom_base, "opt": dom_opt, "red": dom_red
    }

    # --- INTERNATIONAL ENGINE ---
    int_data = {}
    for name, code in GLOBAL_ZONES.items():
        int_data[name] = fetch_live_intensity(code)

    best_int_name = min(int_data, key=int_data.get)
    best_int_val = int_data[best_int_name]

    int_opt = best_int_val * kw * dur
    int_red = dom_base - int_opt

    int_res = {
        "best_zone": best_int_name, # THIS NOW PASSES FULL NAME
        "best_intensity": best_int_val,
        "opt": int_opt, "red": int_red
    }

    inputs = {"home_zone": home_zone_name, "kw": kw, "dur": dur}

    # Artifacts
    adv = rag_pipeline(dom_red, int_red)
    pdf = create_strategic_pdf(dom_res, int_res, adv, inputs)
    z1 = create_evidence_zip(dom_res, "Domestic")
    z2 = create_evidence_zip(int_res, "International")

    return (
        f"{dom_base:.0f} gCO2",
        f"{dom_opt:.0f} gCO2", f"{dom_red:.0f} g", f"✅ {best_dom_name}",
        f"{int_opt:.0f} gCO2", f"{int_red:.0f} g", f"⚠️ {best_int_name}",
        adv, pdf, z1, z2
    )

