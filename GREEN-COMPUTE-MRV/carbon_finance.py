embedder = SentenceTransformer(EMBEDDING_MODEL)

def fetch_live_intensity(zone_code):
    headers = {"auth-token": os.environ["EM_KEY"]}
    try:
        url = "https://api.electricitymap.org/v3/carbon-intensity/latest"
        r = requests.get(url, headers=headers, params={"zone": zone_code}, timeout=4)
        if r.status_code == 200:
            return r.json().get('carbonIntensity', FALLBACK_INTENSITY)
        elif r.status_code in [401, 403] and "-" in zone_code:
             return fetch_live_intensity(zone_code.split("-")[0])
    except: pass
    return FALLBACK_INTENSITY

def rag_pipeline(domestic_red, global_red):
    if not (os.environ["OPENAI_KEY"] and os.environ["PINECONE_KEY"]): return "Advisory Unavailable."
    try:
        query = "cross border data transfer carbon reduction reporting risks"
        vector = embedder.encode(query).tolist()
        pc = Pinecone(api_key=os.environ["PINECONE_KEY"])
        idx = pc.Index(host=PINECONE_HOST)
        res = idx.query(vector=vector, top_k=2, include_metadata=True)
        context = "\n".join([m.metadata.get('text', '') for m in res.matches]) if res.matches else ""

        client = OpenAI(api_key=os.environ["OPENAI_KEY"])
        sys = (
            "You are a Strategic Sustainability Consultant (MBB/Big 4 Style). "
            "Write a concise executive briefing. "
            "Use clear headings (###). "
            "1. Compare Domestic vs. International options. "
            "2. Highlight 'Data Sovereignty' risks for International. "
            "3. Recommend a hybrid approach."
        )
        user = f"Context: {context}\nData: Domestic Savings {domestic_red:.0f}g vs International {global_red:.0f}g."

        resp = client.chat.completions.create(model="gpt-4o-mini", messages=[{"role":"system","content":sys},{"role":"user","content":user}])
        return resp.choices[0].message.content
    except Exception as e: return f"Error: {e}"

