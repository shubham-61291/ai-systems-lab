def roc_data(res):
    vals = [q["correctness"] for q in res["per_question"] if q["correctness"] is not None]
    if not vals:
        return [], []
    th = np.linspace(0, 1, 50)
    fr = [(sum(1 for v in vals if v >= t) / len(vals)) for t in th]
    return th, fr

