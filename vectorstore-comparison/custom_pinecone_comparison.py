retrieval_threshold = 0.40

def evaluate_system(search_fn, label):
    per_q = []
    recall = 0.0
    precision = 0.0
    mrr = 0.0
    ndcg = 0.0
    correctness_scores = []
    faithfulness_scores = []

    n = len(questions)

    for q in questions:
        qvec = embed(q)

        # timed retrieval
        rt1 = time.time()
        retrieved = search_fn(qvec, 3)  # search_fn expects (qvec, k)
        rt2 = time.time()
        retrieval_latency = rt2 - rt1

        sims = [s for _, s in retrieved]

        # recall
        if sims and max(sims) >= retrieval_threshold:
            recall += 1.0

        # precision
        if sims:
            precision += sum(1 for s in sims if s >= retrieval_threshold) / 3.0
        else:
            precision += 0.0

        # mrr
        rank = None
        for i, s in enumerate(sims):
            if s >= retrieval_threshold:
                rank = i + 1
                break
        mrr += (1.0 / rank) if rank else 0.0

        # ndcg
        gains = [s if s >= retrieval_threshold else 0.0 for s in sims]
        if gains:
            dcg = sum(g / log2(i + 2) for i, g in enumerate(gains))
            ideal = sorted(gains, reverse=True)
            idcg = sum(v / log2(i + 2) for i, v in enumerate(ideal))
            ndcg += (dcg / idcg) if idcg > 0 else 0.0
        else:
            ndcg += 0.0

        # LLM judge
        chunks_used = [t for t, _ in retrieved]

        llm1 = time.time()
        ans = nano_answer(q, chunks_used)
        llm2 = time.time()
        llm_latency = llm2 - llm1
        total_latency = retrieval_latency + llm_latency

        judge = (
            "You are a strict evaluator.\n"
            "Rate the answer on two metrics:\n"
            "1. Correctness (0 to 1)\n"
            "2. Faithfulness to context (0 to 1)\n\n"
            "Reply EXACTLY in format:\n"
            "C=0.x F=0.x\n\n"
            f"QUESTION:\n{q}\n\nANSWER:\n{ans}"
        )

        C = None
        F = None
        try:
            resp = client.responses.create(
                model="gpt-4.1-mini",
                input=judge,
                max_output_tokens=40
            )
            txt = resp.output_text or ""
            C = float(re.findall(r"C=([0-9.]+)", txt)[0])
            F = float(re.findall(r"F=([0-9.]+)", txt)[0])
            correctness_scores.append(C)
            faithfulness_scores.append(F)
        except Exception:
            C = F = None

        per_q.append({
            "question": q,
            "sims": sims,
            "retrieval_latency": retrieval_latency,
            "llm_latency": llm_latency,
            "total_latency": total_latency,
            "correctness": C,
            "faithfulness": F
        })

    # Averages
    avg_recall = recall / n if n > 0 else 0.0
    avg_precision = precision / n if n > 0 else 0.0
    avg_mrr = mrr / n if n > 0 else 0.0
    avg_ndcg = ndcg / n if n > 0 else 0.0
    avg_correctness = (sum(correctness_scores)/len(correctness_scores)) if correctness_scores else 0.0
    avg_faithfulness = (sum(faithfulness_scores)/len(faithfulness_scores)) if faithfulness_scores else 0.0

    results = {
        "label": label,
        "recall": avg_recall,
        "precision": avg_precision,
        "mrr": avg_mrr,
        "ndcg": avg_ndcg,
        "correctness": avg_correctness,
        "faithfulness": avg_faithfulness,
        "per_question": per_q
    }

    print("\n===============================")
    print("📊 RESULTS:", label)
    print("===============================")

    for k, v in results.items():
        if k in ["label", "per_question"]:
            print(k, "=", v)
        else:
            print(k, "=", round(float(v), 3))

    print("===============================\n")

    return results

