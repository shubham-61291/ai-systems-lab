class VectorDB:
    def __init__(self):
        self.vecs = []
        self.texts = []

    def add(self, vec, text):
        self.vecs.append(vec)
        self.texts.append(text)

    def search(self, query_vec, k=3):
        if not self.vecs:
            return []
        A = np.array(self.vecs)
        qn = np.linalg.norm(query_vec)
        dn = np.linalg.norm(A, axis=1)
        sims = np.dot(A, query_vec) / (dn * qn + 1e-9)
        idx = sims.argsort()[-k:][::-1]
        return [(self.texts[i], float(sims[i])) for i in idx]

