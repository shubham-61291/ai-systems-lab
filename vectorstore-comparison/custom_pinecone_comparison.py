def pine_search(qvec, k=3):
    res = pine.query(
        vector=qvec.tolist(),
        top_k=k,
        include_metadata=True
    )
    # handle both object + dict style just in case
    matches = getattr(res, "matches", None)
    if matches is None:
        matches = res["matches"]
    out = []
    for m in matches:
        meta = getattr(m, "metadata", m["metadata"])
        score = getattr(m, "score", m["score"])
        out.append((meta["text"], float(score)))
    return out

