def clean_data_engine(input_file):
    print(f"[Engine] Ingesting: {input_file}")
    try:
        with open(input_file, 'r', encoding='utf-8-sig') as f:
            raw = json.load(f)
    except Exception as e:
        print(f"[Engine] JSON Load Error: {e}")
        return []

    atoms = []

    # --------------------------------------------------------------------------
    # TRAINING EXAMPLES
    # --------------------------------------------------------------------------
    if "training_examples" in raw:
        print(f"[Engine] Found {len(raw['training_examples'])} training examples")

        for example in raw["training_examples"]:
            user_input = example.get("user_input", "").strip()
            if not user_input:
                continue

            assistant_output = example.get("assistant_output", "")
            assistant_text = ""

            if isinstance(assistant_output, dict):
                def flatten_dict(d, prefix=""):
                    items = []
                    for key, value in d.items():
                        new_key = f"{prefix}.{key}" if prefix else key
                        if isinstance(value, dict):
                            items.extend(flatten_dict(value, new_key))
                        elif isinstance(value, list):
                            list_items = []
                            for i, item in enumerate(value):
                                if isinstance(item, dict):
                                    list_items.extend(flatten_dict(item, f"{new_key}[{i}]"))
                                else:
                                    list_items.append(f"• {item}")
                            items.append(f"{new_key}:\n" + "\n".join(list_items))
                        else:
                            items.append(f"{new_key}: {value}")
                    return items

                assistant_text = "\n".join(flatten_dict(assistant_output))

            elif isinstance(assistant_output, list):
                assistant_text = "\n".join([f"• {item}" for item in assistant_output if item])

            elif isinstance(assistant_output, str):
                assistant_text = assistant_output
            else:
                assistant_text = str(assistant_output)

            assistant_text = assistant_text.strip()

            if assistant_text:
                atoms.append(
                    f"<|user|>{user_input}<|endoftext|><|system|>{assistant_text}<|endoftext|>"
                )

                if "simple_definition" in assistant_text or "explanation" in assistant_text.lower():
                    atoms.append(
                        f"<|system|>{assistant_text}<|endoftext|><|user|>{user_input}<|endoftext|>"
                    )

    # --------------------------------------------------------------------------
    # MULTI-TURN CONVERSATIONS
    # --------------------------------------------------------------------------
    if "multi_turn_conversations" in raw:
        print(f"[Engine] Found {len(raw['multi_turn_conversations'])} multi-turn conversations")

        for conv in raw["multi_turn_conversations"]:
            if "turns" in conv:
                conversation_text = ""
                for turn in conv["turns"]:
                    speaker = turn.get("speaker", "Speaker")
                    content = turn.get("content", "").strip()
                    if content:
                        conversation_text += f"{speaker}: {content}\n"

                if conversation_text:
                    atoms.append(
                        f"<|system|>Multi-turn conversation on "
                        f"{conv.get('domain', 'business')}:\n"
                        f"{conversation_text}<|endoftext|>"
                    )

    # --------------------------------------------------------------------------
    # ASSESSMENT ITEMS
    # --------------------------------------------------------------------------
    if "assessment_items" in raw:
        print(f"[Engine] Found {len(raw['assessment_items'])} assessment items")

        for item in raw["assessment_items"]:
            if item.get("type") == "multiple_choice":
                question = item.get("question", "").strip()
                options = item.get("options", {})
                correct = item.get("correct_answer", "")
                explanation = item.get("explanation", "")

                if question and options:
                    options_text = "\n".join([f"{k}: {v}" for k, v in options.items()])
                    assessment_text = (
                        f"Question: {question}\n"
                        f"Options:\n{options_text}\n"
                        f"Correct Answer: {correct}\n"
                        f"Explanation: {explanation}"
                    )
                    atoms.append(
                        f"<|user|>Test question:<|endoftext|>"
                        f"<|system|>{assessment_text}<|endoftext|>"
                    )

    # --------------------------------------------------------------------------
    # DOCUMENT-STYLE POLICY INGEST
    # --------------------------------------------------------------------------
    if "sections" in raw:
        print("[Engine] Found document-style policy structure")

        for section in raw["sections"]:
            section_atoms = []
            section_atoms.append(
                f"Section {section.get('section_number', '')}: {section.get('title', '')}"
            )

            for sub in section.get("subsections", []):
                section_atoms.append(
                    f"{sub.get('subsection_number', '')} {sub.get('title', '')}"
                )

                for key, value in sub.items():
                    if isinstance(value, str):
                        section_atoms.append(value)
                    elif isinstance(value, list):
                        for item in value:
                            if isinstance(item, str):
                                section_atoms.append(f"- {item}")
                            elif isinstance(item, dict):
                                for _, v in item.items():
                                    if isinstance(v, str):
                                        section_atoms.append(v)

            joined = "\n".join(section_atoms).strip()
            if joined:
                atoms.append(f"<|system|>{joined}<|endoftext|>")

    print(f"[Engine] Total atoms generated: {len(atoms)}")
    return atoms

