# 5. STRATEGIC CONTRAST
# =========================================================
def calculate_resonance(metrics, brand_name):
    words = metrics.get("word_cloud", [])
    brand = brand_name.lower()

    def is_mixed_token(t: str) -> bool:
        t = (t or "").lower()
        return "/" in t or "&" in t

    fgc_vol = sum(
        w.get("MENTIONS__SUM", 0)
        for w in words
        if brand in str(w.get("WORD_CLOUD", "")).lower()
        and not is_mixed_token(str(w.get("WORD_CLOUD", "")))
    )
    total_vol = sum(w.get("MENTIONS__SUM", 0) for w in words)
    return (fgc_vol / total_vol * 100) if total_vol > 0 else 0

def analyze_strategy_comparison(buckets, b1, b2):
    def get_neg_ratio(s):
        pos = s.get("POSITIVE_MENTIONS__SUM", 0)
        neg = s.get("NEGATIVE_MENTIONS__SUM", 0)
        total = pos + neg
        return (neg / total) if total > 0 else 0

    res_a = calculate_resonance(buckets[b1], b1)
    res_b = calculate_resonance(buckets[b2], b2)

    neg_a = get_neg_ratio(buckets[b1]["sentiment"])
    neg_b = get_neg_ratio(buckets[b2]["sentiment"])

    return f"""
### Competitive Strategic Audit: {b1} vs {b2}

| Strategic Pillar | {b1} | {b2} |
|---|---|---|
| Narrative Capture (FGC) | {res_a:.2f}% | {res_b:.2f}% |
| Community Agency (UGC) | {100-res_a:.2f}% | {100-res_b:.2f}% |
| Crisis Exposure | {neg_a*100:.1f}% | {neg_b*100:.1f}% |
"""

