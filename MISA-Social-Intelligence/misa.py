def load_rows(file_path: str) -> List[Dict[str, Any]]:
    with open(file_path, "r", encoding="utf-8") as f:
        raw = f.read().strip()

    if not raw:
        return []

    if raw.lstrip().startswith("["):
        obj = json.loads(raw)
        if isinstance(obj, list):
            return obj
        raise ValueError("JSON array file did not contain a list.")

    rows = []
    for line in raw.splitlines():
        line = line.strip()
        if not line:
            continue
        rows.append(json.loads(line))
    return rows

# =========================================================
# 3. BRAND DETECTION FROM DATA
# =========================================================
def detect_brands_from_data(rows: List[Dict[str, Any]], top_n: int = 2) -> List[str]:
    wc_rows = [
        r for r in rows
        if isinstance(r.get("WORD_CLOUD"), str)
        and isinstance(r.get("MENTIONS__SUM"), (int, float))
    ]

    if not wc_rows:
        raise ValueError("No WORD_CLOUD rows found.")

    df = pd.DataFrame(wc_rows)
    df["TOKEN"] = df["WORD_CLOUD"].str.strip().str.lower()
    df = df[df["TOKEN"].str.fullmatch(r"[@#]?[a-z][a-z0-9\-\&']{2,}")]

    scores = df.groupby("TOKEN")["MENTIONS__SUM"].sum().sort_values(ascending=False)
    brands = [t.lstrip("#@").title() for t in scores.head(top_n).index.tolist()]

    if len(brands) < top_n:
        raise ValueError(f"Could not detect {top_n} brands. Found: {brands}")

    return brands

