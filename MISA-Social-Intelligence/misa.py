# 4. DATA INTEGRITY & SPLITTER (PAIRWISE MODE: ONE BRAND PER FILE)
# =========================================================
def validate_and_split_single_brand(rows: List[Dict[str, Any]]):
    brand = detect_brands_from_data(rows, top_n=1)[0]
    brand_low = brand.lower()

    buckets = {
        brand: {"sentiment": {}, "word_cloud": [], "stakeholders": [], "country": []}
    }

    global_sentiment = None
    for r in rows:
        if (
            "POSITIVE_MENTIONS__SUM" in r
            and "NEGATIVE_MENTIONS__SUM" in r
            and "NEUTRAL_MENTIONS__SUM" in r
            and "WORD_CLOUD" not in r
            and "HASHTAG" not in r
        ):
            global_sentiment = r
            break

    if isinstance(global_sentiment, dict):
        buckets[brand]["sentiment"] = {
            "POSITIVE_MENTIONS__SUM": global_sentiment.get("POSITIVE_MENTIONS__SUM", 0),
            "NEGATIVE_MENTIONS__SUM": global_sentiment.get("NEGATIVE_MENTIONS__SUM", 0),
            "NEUTRAL_MENTIONS__SUM": global_sentiment.get("NEUTRAL_MENTIONS__SUM", 0),
        }
    else:
        buckets[brand]["sentiment"] = {
            "POSITIVE_MENTIONS__SUM": 0,
            "NEGATIVE_MENTIONS__SUM": 0,
            "NEUTRAL_MENTIONS__SUM": 0,
        }

    for r in rows:
        if isinstance(r.get("WORD_CLOUD"), str):
            token = r["WORD_CLOUD"].lower()
            buckets[brand]["word_cloud"].append(r)
            if token.startswith("@"):
                buckets[brand]["stakeholders"].append(r)

    for r in rows:
        if "COUNTRY" in r and isinstance(r.get("MENTIONS__SUM"), (int, float)):
            buckets[brand]["country"].append(r)

    status = f"✅ FILE-ALIGNED: Brand derived → {brand}"
    return buckets, brand, status

