def run_pipeline(files):
    if not files or len(files) < 2:
        raise ValueError("Upload at least 2 files.")

    data_a = load_rows(files[0].name)
    data_b = load_rows(files[1].name)

    buckets_a, b1, _ = validate_and_split_single_brand(data_a)
    buckets_b, b2, _ = validate_and_split_single_brand(data_b)

    buckets = {**buckets_a, **buckets_b}

    ai_input = {b1: buckets[b1]["sentiment"], b2: buckets[b2]["sentiment"]}

    advisory = client.chat.completions.create(
        model=MODEL_NAME,
        messages=[
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": f"Compare {b1} vs {b2}: {json.dumps(ai_input)}"}
        ]
    ).choices[0].message.content

    audit_md = analyze_strategy_comparison(buckets, b1, b2)
    p1, p2, p3, p4 = get_plots(buckets, b1, b2)

    status = "✅ PAIRWISE MODE: first 2 uploaded files used"
    return advisory, audit_md, p1, p2, p3, p4, status

