    v1 = [s1.get("POSITIVE_MENTIONS__SUM", 0), s1.get("NEGATIVE_MENTIONS__SUM", 0), s1.get("NEUTRAL_MENTIONS__SUM", 0)]
    v2 = [s2.get("POSITIVE_MENTIONS__SUM", 0), s2.get("NEGATIVE_MENTIONS__SUM", 0), s2.get("NEUTRAL_MENTIONS__SUM", 0)]
    x = range(len(labels))
    plt.bar([i - 0.2 for i in x], v1, width=0.4, label=b1)
    plt.bar([i + 0.2 for i in x], v2, width=0.4, label=b2)
    plt.xticks(list(x), labels)
    plt.title("Sentiment Mentions")
    plt.legend()
    plt.tight_layout()

    # Plot 2: Top 10 WORD_CLOUD tokens for b1
    fig2 = plt.figure()
    wc1 = buckets[b1].get("word_cloud", [])
    if wc1:
        df1 = pd.DataFrame(wc1)
