class RAGBuilderServer:
    """Upload docs → build Pinecone index → retrieve chunks."""

    def __init__(self):
        self.documents = {}
        self.doc_counter = 0

    def upload_document(self, text: str, filename: str):
        if not text.strip():
            return "❌ Document text is empty."
        self.doc_counter += 1
        doc_id = f"doc_{self.doc_counter}"
        self.documents[doc_id] = {
            "filename": filename or f"document_{self.doc_counter}.txt",
            "text": text,
        }
        return f"✅ Document uploaded as {doc_id} (filename: {self.documents[doc_id]['filename']})."

    def build_vector_db(self):
        """Chunk all docs, embed, and upsert to Pinecone."""
        if not self.documents:
            return "❌ No documents uploaded. Please upload at least one document."

        total_chunks = 0
        vectors_to_upsert = []

        for doc_id, doc in self.documents.items():
            chunks = chunk_text(doc["text"])
            embeddings = embed_texts(chunks)

            for idx, (chunk_text_str, vec) in enumerate(zip(chunks, embeddings)):
                vectors_to_upsert.append(
                    (
                        f"{doc_id}_chunk_{idx}",
                        vec.tolist(),
                        {
                            "doc_id": doc_id,
                            "filename": doc["filename"],
                            "chunk_index": idx,
                            "text": chunk_text_str,
                        },
                    )
                )
                total_chunks += 1

        if vectors_to_upsert:
            pinecone_index.upsert(vectors=vectors_to_upsert)

        return f"✅ Vector DB built successfully. Indexed {len(self.documents)} docs, {total_chunks} chunks."

    def retrieve_chunks(self, query: str, top_k: int = 3):
        """Retrieve top_k most relevant chunks from Pinecone."""
        if not query.strip():
            return ["❌ Query is empty."]

        query_vec = embed_texts([query])[0]
        res = pinecone_index.query(
            vector=query_vec.tolist(),
            top_k=top_k,
            include_metadata=True,
        )

        if not res.matches:
            return ["ℹ️ No relevant chunks found. Upload documents and rebuild DB."]

        chunks = []
        for match in res.matches:
            md = match.metadata or {}
            text = md.get("text", "")
            score = match.score
            chunks.append(f"[score={score:.3f}] {text}")
        return chunks

class RAGTestingServer:
    """Evaluate answers: semantic relevance + LLM-based faithfulness."""

    def evaluate_answer(self, query: str, answer: str):
        if not query.strip() or not answer.strip():
            return {"error": "Query or answer is empty."}

        q_vec = embed_texts([query])[0]
        a_vec = embed_texts([answer])[0]
        cos_sim = compute_cosine_similarity(q_vec, a_vec)
        semantic_relevance = (cos_sim + 1) / 2.0
        semantic_relevance = float(np.clip(semantic_relevance, 0.0, 1.0))
        semantic_relevance = round(semantic_relevance, 3)

        eval_prompt = f"""
You are evaluating how faithful an answer is to a query.

Query:
{query}

Answer:
{answer}

On a scale from 0.0 to 1.0:
- 1.0 = fully faithful and accurate
- 0.0 = completely unfaithful or hallucinated

Respond with ONLY a number between 0.0 and 1.0.
"""

        try:
            resp = openai_client.responses.create(
                model="gpt-4.1-mini",
                input=eval_prompt,
                max_output_tokens=10,
            )
            raw = resp.output_text.strip()
            faithfulness = float(raw)
            if not (0.0 <= faithfulness <= 1.0):
                raise ValueError("Out of range")
        except Exception:
            faithfulness = 0.5

        faithfulness = round(faithfulness, 3)
        overall_confidence = round((semantic_relevance + faithfulness) / 2.0, 3)

        def label(score):
            if score >= 0.8:
                return "High"
            elif score >= 0.5:
                return "Medium"
            else:
                return "Low"

        return {
            "semantic_relevance": semantic_relevance,
            "semantic_relevance_label": label(semantic_relevance),
            "answer_faithfulness": faithfulness,
            "answer_faithfulness_label": label(faithfulness),
            "overall_confidence": overall_confidence,
            "overall_confidence_label": label(overall_confidence),
        }

