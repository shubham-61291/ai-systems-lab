def generate_rag_answer(question: str, top_k: int = 3):
    if not question.strip():
        return "❌ Question is empty."

    chunks = rag_builder.retrieve_chunks(question, top_k=top_k)
    context = "\n\n".join(chunks)

    prompt = f"""
You are a helpful assistant answering questions using ONLY the given context.

Context:
{context}

Question:
{question}

If the context is insufficient, clearly say you are not sure instead of hallucinating.
Answer concisely.
"""

    resp = openai_client.responses.create(
        model="gpt-4.1-mini",
        input=prompt,
        max_output_tokens=512,
    )
    return resp.output_text.strip()

