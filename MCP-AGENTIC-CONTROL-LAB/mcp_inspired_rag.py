def compute_cosine_similarity(v1, v2):
    """Cosine similarity between two vectors."""
    v1 = np.array(v1, dtype=np.float32)
    v2 = np.array(v2, dtype=np.float32)
    denom = np.linalg.norm(v1) * np.linalg.norm(v2)
    if denom == 0:
        return 0.0
    return float(np.dot(v1, v2) / denom)

def core_pinecone_upsert(text_to_update, embedding_model, pinecone_index):
    """
    Core function: Updates/upserts text directly to Pinecone.
    USING TUPLE FORMAT (id, vector, metadata) FOR CONSISTENCY
    """
    try:
        embedding = embedding_model.encode(text_to_update).tolist()
        vector_id = f"update_{int(time.time())}"
        metadata = {
            "source": "Direct_Update",
            "timestamp": time.strftime("%Y-%m-%d %H:%M:%S"),
            "text": text_to_update,
        }
        pinecone_index.upsert(
            vectors=[(vector_id, embedding, metadata)]
        )
        verify = pinecone_index.query(
            vector=embedding,
            top_k=1,
            include_metadata=True
        )
        return f"✅ Updated successfully. ID: {vector_id}"
    except Exception as e:
        return f"❌ Update failed: {str(e)}"

