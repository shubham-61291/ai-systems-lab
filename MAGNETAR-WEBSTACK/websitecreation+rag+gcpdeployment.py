# ============== MAIN BUILD ==============
def build_site(
    prompt: str,
    rag_enabled: bool,
    documents: Optional[List[gr.File]],
    cloud_enabled: bool,
    deploy: bool,
    bucket: str,
    gcp_key: Optional[gr.File],
):
    """
    Final aligned flow:
    1) Website prompt -> build HTML
    2) Optional RAG -> requires documents, inject Bot + lazy embeddings in-browser
    3) Optional Cloud -> deploy if requested
    """
    # 1) Generate base HTML
    client = OpenAI(api_key=OPENAI_API_KEY)

    resp = client.chat.completions.create(
        model=MODEL_NAME,
        messages=[
            {"role":"system","content":"Return a full HTML document only."},
            {"role":"user","content":prompt}
        ]
    )

    base_html = strip_fences(resp.choices[0].message.content)

    # 2) If RAG enabled, require docs
    doc_chunks = []
    if rag_enabled:
        docs_text = extract_documents_text(documents)
        docs_text = normalize_whitespace(docs_text)

        if not docs_text:
            # Fail early with clean message in preview
            # (Still return site, but RAG won't be functional)
            doc_chunks = ["No documents were provided. Rebuild with document upload enabled."]
        else:
            doc_chunks = chunk_text(docs_text, size_words=350, overlap_words=60, max_chunks=120)

    # 3) Inject modules based on product flow
    final_html = inject_all(
        base_html=base_html,
        rag_enabled=rag_enabled,
        doc_chunks=doc_chunks,
        cloud_enabled=cloud_enabled,
    )

    # Save + zip
    zip_path, _ = save_site(final_html)

    # Deploy logic (only if deploy requested)
    deploy_status = "Not deployed"
    if deploy:
        if not bucket or not bucket.strip():
            deploy_status = "DEPLOY FAILED: Bucket name required"
        elif gcp_key is None:
            deploy_status = "DEPLOY FAILED: Upload GCP JSON key"
        else:
            deploy_status = deploy_to_gcp(final_html, gcp_key.name, bucket.strip())

    return final_html, iframe_preview(final_html), zip_path, deploy_status


