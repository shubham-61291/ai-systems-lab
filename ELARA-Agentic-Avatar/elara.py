def ensure_pcm_16k(input_path, output_path):
  """Normalizes audio for Google STT"""
  out = run(["ffmpeg", "-y", "-i", input_path, "-ac", "1", "-ar", "16000", "-f", "wav", "-acodec", "pcm_s16le", output_path])
  if out.returncode == 0 and os.path.exists(output_path):
    return output_path
  shutil.copyfile(input_path, output_path)
  return output_path

def google_stt(audio_filepath, credentials_path):
  """Runs Google Speech-to-Text"""
  print(f"🎤 STT: {audio_filepath}")
  if not audio_filepath or not os.path.exists(audio_filepath):
    return ""
  os.environ["GOOGLE_APPLICATION_CREDENTIALS"] = credentials_path
  normalized = USER_AUDIO_PATH.replace(".wav", "_16k.wav")
  norm = ensure_pcm_16k(audio_filepath, normalized)
  if not os.path.exists(norm):
    return ""

  client = speech.SpeechClient()
  with open(norm, "rb") as f:
    content = f.read()

  audio = speech.RecognitionAudio(content=content)
  config = speech.RecognitionConfig(
    encoding=speech.RecognitionConfig.AudioEncoding.LINEAR16,
    sample_rate_hertz=16000,
    language_code="en-US",
    audio_channel_count=1
  )
  resp = client.recognize(config=config, audio=audio)
  if resp.results:
    return resp.results[0].alternatives[0].transcript
  return ""

def get_elara_response(user_text, chat_history, api_key):
  """Gets a response from Elara's brain (OpenAI)"""
  if len(chat_history) == 0:
    return ELARA_OPENING_LINE

  messages = [{"role": "system", "content": ELARA_SYSTEM_PROMPT}]
  for m in chat_history:
    if isinstance(m, dict) and "role" in m and "content" in m:
      messages.append(m)
  messages.append({"role": "user", "content": user_text})

  if not api_key or not api_key.strip():
    return "Please provide your OpenAI API key."

  client = OpenAI(api_key=api_key)

  try:
    # --- Try gpt-5-nano first (as in original doc) ---
    resp = client.responses.create(
      model="gpt-5-nano",
      input=messages,
      modalities=["text"],
      response_format={"type": "text"},
      max_output_tokens=1000
    )
    text = getattr(resp, "output_text", None)
    if not text:
        parts = []
        for item in getattr(resp, "output", []) or []:
            for c in getattr(item, "content", []) or []:
                if getattr(c, "type", "") == "output_text" and getattr(c, "text", None):
                    parts.append(c.text)
        text = " ".join(parts) if parts else ""
    return text or "Sorry, there was an issue. Please try again."

  except Exception as e_nano:
    print(f"gpt-5-nano failed: {e_nano}. Falling back to gpt-4o-mini.")
    try:
        # --- Fallback to gpt-4o-mini ---
        chat_messages = [m for m in messages if m['role'] in ('system', 'user', 'assistant')]
        resp_mini = client.chat.completions.create(
            model="gpt-4o-mini",
            messages=chat_messages,
            max_tokens=300
        )
        text = resp_mini.choices[0].message.content
        return text or "Sorry, there was an issue. Please try again."
    except Exception as e_mini:
        print(f"gpt-4o-mini also failed: {e_mini}")
        return f"Sorry, an error occurred: {e_mini}"


def google_tts(text, credentials_path, output_path):
  """Runs Google Text-to-Speech"""
  os.environ["GOOGLE_APPLICATION_CREDENTIALS"] = credentials_path
  client = texttospeech.TextToSpeechClient()
  synthesis_input = texttospeech.SynthesisInput(text=text)
  voice = texttospeech.VoiceSelectionParams(language_code="en-US", name="en-US-Wavenet-F")
  audio_config = texttospeech.AudioConfig(audio_encoding=texttospeech.AudioEncoding.LINEAR16, sample_rate_hertz=44100)
  resp = client.synthesize_speech(input=synthesis_input, voice=voice, audio_config=audio_config)
  with open(output_path, "wb") as out:
    out.write(resp.audio_content)
  return output_path

