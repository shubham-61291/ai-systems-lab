def as_messages(history_list):
  """Converts Gradio chat history to OpenAI message format"""
  msgs = []
  if not history_list:
    return msgs
  for item in history_list:
    if isinstance(item, dict) and "role" in item and "content" in item:
      msgs.append({"role": item["role"], "content": item["content"]})
    elif isinstance(item, (list, tuple)) and len(item) == 2:
      u, a = item
      if u:
        msgs.append({"role": "user", "content": u})
      if a:
        msgs.append({"role": "assistant", "content": a})
  return msgs

def process_input(openai_api_key, gcp_key_file, avatar_image, user_audio, user_text, chat_history):
  """Main Gradio event handler"""
  if chat_history is None:
    chat_history = []

  current_history = as_messages(copy.deepcopy(chat_history))

  yield current_history, current_history, None, None, "🔄 Preparing files..."

  # --- 1. Check & Copy GCP Key ---
  if not gcp_key_file or not (isinstance(gcp_key_file, str) and os.path.exists(gcp_key_file)):
    yield current_history, current_history, None, None, "❌ Upload Google Cloud key (.json)"
    return
  shutil.copyfile(gcp_key_file, GCP_KEY_PATH)

  # --- 2. Check & Prepare Avatar Image ---
  if avatar_image is not None:
    if avatar_image.mode in ('RGBA', 'LA', 'P'):
      avatar_image = avatar_image.convert('RGB')
    w, h = avatar_image.size
    if (w, h) != (512, 512):
      avatar_image = avatar_image.resize((512, 512), Image.Resampling.LANCZOS)
    avatar_image.save(AVATAR_IMAGE_PATH, format="PNG")
  elif not os.path.exists(AVATAR_IMAGE_PATH):
    # Create a default purple image if none is uploaded
    img = Image.new('RGB', (512, 512), color='#6366f1')
    img.save(AVATAR_IMAGE_PATH, format="PNG")

  # --- 3. Check & Copy User Audio ---
  if user_audio:
    if isinstance(user_audio, str) and os.path.exists(user_audio):
      shutil.copyfile(user_audio, USER_AUDIO_PATH)
    else:
      yield current_history, current_history, None, None, "❌ Invalid audio input"
      return

  # --- 4. Get User Input (STT or Text) ---
  yield current_history, current_history, None, None, "🔄 Transcribing or reading text..."
  if user_audio:
    input_text = google_stt(USER_AUDIO_PATH, GCP_KEY_PATH)
    if not input_text:
      yield current_history, current_history, None, None, "❌ Could not transcribe audio"
      return
  elif user_text and user_text.strip():
    input_text = user_text.strip()
  else:
    # This is the "Welcome" message trigger
    input_text = ""

  # --- 5. Get Elara Response (OpenAI) ---
  yield current_history, current_history, None, None, "🔄 Generating Elara's response..."
  if not openai_api_key:
    yield current_history, current_history, None, None, "❌ Provide OpenAI API key"
    return

  # *** FIX: Pass the correct variable ***
  elara_text = get_elara_response(input_text, current_history, openai_api_key)

  updated_history = copy.deepcopy(current_history)
  if input_text: # Don't add empty user message on first load
    updated_history.append({"role": "user", "content": input_text})
  updated_history.append({"role": "assistant", "content": elara_text})

  # --- 6. Generate Speech (Google TTS) ---
  yield updated_history, updated_history, None, None, "🔄 Generating speech..."
  tts_audio = google_tts(elara_text, GCP_KEY_PATH, ELARA_TTS_AUDIO_PATH)
  if not os.path.exists(tts_audio):
    yield updated_history, updated_history, None, None, "❌ TTS failed"
    return

  # --- 7. Generate Video (Ditto) ---
  yield updated_history, updated_history, tts_audio, None, "🔄 Rendering video (PyTorch Path)..."

  video_output = run_ditto_pytorch_path(ELARA_TTS_AUDIO_PATH, AVATAR_IMAGE_PATH, OUTPUT_VIDEO_PATH)

  if video_output:
    yield updated_history, updated_history, tts_audio, video_output, "✅ Complete! Animation ready."
  else:
    yield updated_history, updated_history, tts_audio, None, "⚠ Animation failed - audio ready"

