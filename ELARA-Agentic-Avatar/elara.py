  def clear_inputs():
    return None, ""

  app.queue(max_size=None, status_update_rate="auto")

  send_button.click(
    fn=process_input,
    inputs=inputs,
    outputs=outputs,
    concurrency_limit=1,
    concurrency_id="elara_pipeline",
  ).then(fn=clear_inputs, outputs=[user_audio, user_text])

  user_text.submit(
    fn=process_input,
    inputs=inputs,
    outputs=outputs,
    concurrency_limit=1,
    concurrency_id="elara_pipeline",
  ).then(fn=clear_inputs, outputs=[user_audio, user_text])

  # Add a "load" event to trigger the welcome message
